"use strict";
const assert = require("node:assert/strict");
require("./questions-data.js");
const quiz = require("./quiz.js");
const {game,startGame,answer,nextQuestion,scores,useHint,expireQuestion,dailyQuestions,readRecords,saveResult,recordKey} = quiz;
const {validateRecords,summarizeRecords,csvCell} = require("./teacher.js");
const {createReport} = require("./teacher_cli.js");
assert.deepEqual(dailyQuestions("2026-11-10"), dailyQuestions("2026-11-10"));
assert.equal(new Set(dailyQuestions("2026-11-10").map(q=>q.id)).size,10);
assert.notDeepEqual(dailyQuestions("2026-11-10"),dailyQuestions("2026-11-11"));
startGame("speed", "과학", 1000);
assert.equal(expireQuestion(15999),false);
assert.equal(answer(game.questions[0].answer_index,16000),false);
assert.equal(game.answers[0],-1);
assert.equal(expireQuestion(17000),false);
assert.equal(scores().points,0);
nextQuestion();
assert.equal(useHint(),true); assert.equal(useHint(),false);
assert.equal(answer(game.questions[1].answer_index),true);
assert.equal(scores().points,8);
assert.equal(useHint(),false);
const map = new Map(); const storage = {getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
for (const mode of ["normal","speed","practice","daily"]) {
  startGame(mode,"컴퓨터공학");
  assert.equal(game.questions.length,mode==="normal"||mode==="speed"?50:10);
  if(mode==="normal") assert.equal(useHint(),false);
  for(const q of game.questions) { answer(q.answer_index); nextQuestion(); }
  assert.equal(saveResult("학습자",storage),true);
  assert.equal(saveResult("중복",storage),false);
  assert.equal(readRecords(storage,mode).length,1);
  assert.equal(scores().points,mode==="speed"?500:game.questions.length);
}
assert.equal(map.size,4);
const exported = {version:1,records:[...map.values()].flatMap(JSON.parse)};
const records = validateRecords(exported);
assert.equal(summarizeRecords(records,"speed").rows[0].grade,"A");
assert.equal(summarizeRecords(records,"practice").average,100);
assert.throws(()=>validateRecords({version:1,records:[null]}));
for(const edit of [{total:51},{name:""},{points:501},{points:0},{questionCount:10},{byCategory:{}},{completedAt:"bad"}]) assert.throws(()=>validateRecords({version:1,records:[{...records[0],...edit}]}));
assert.equal(summarizeRecords([],"normal").average,0);
assert.ok(csvCell("=1+1").startsWith('"\''));
const hostile = [{...records[0],name:"<img src=x>"}];
assert.ok(createReport(hostile,"normal","html").includes("&lt;img src=x&gt;"));
assert.ok(!createReport(hostile,"normal","html").includes("<img src=x>"));
assert.throws(()=>createReport(records,"invalid","csv"));
map.set(recordKey("daily"),"{");
assert.throws(()=>readRecords(storage,"daily"));
assert.equal(map.get(recordKey("daily")),"{");
console.log("PASS: modes, deadlines, hints, daily selection, isolated records, reports, input validation and output escaping.");
